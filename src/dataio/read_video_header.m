function hdr = read_video_header(videoPath)
%READ_VIDEO_HEADER  Video properties stored in the file header.
%   hdr = read_video_header(videoPath)
%   hdr fields: Path, Width, Height, FrameRate, NumFrames, Duration, VideoFormat

arguments
    videoPath (1,1) string {mustBeFile}
end

v = VideoReader(videoPath);
hdr = struct( ...
    "Path",        string(fullfile(v.Path, v.Name)), ...
    "Width",       v.Width, ...
    "Height",      v.Height, ...
    "FrameRate",   v.FrameRate, ...
    "NumFrames",   v.NumFrames, ...
    "Duration",    v.Duration, ...
    "VideoFormat", string(v.VideoFormat));
end
