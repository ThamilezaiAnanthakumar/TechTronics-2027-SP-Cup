import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

// Writes dist/sw.js after the build: a cache-first service worker that
// precaches every built file (app, MediaPipe WASM, face model), so the app
// runs offline after the first load and makes no network requests.
function precacheServiceWorker(): Plugin {
  let outDir = 'dist';
  return {
    name: 'facevitals-precache-sw',
    apply: 'build',
    configResolved(c) { outDir = c.build.outDir; },
    closeBundle() {
      const files: string[] = [];
      const walk = (d: string) => {
        for (const f of readdirSync(d)) {
          const p = join(d, f);
          if (statSync(p).isDirectory()) walk(p);
          else if (f !== 'sw.js' && !f.endsWith('.map')) files.push(relative(outDir, p).split(sep).join('/'));
        }
      };
      walk(outDir);
      const h = createHash('sha256');
      for (const f of files.sort()) h.update(f).update(readFileSync(join(outDir, f)));
      const version = h.digest('hex').slice(0, 12);
      const urls = ['./', ...files];
      const sw = `// generated by vite.config.ts — do not edit
const CACHE = 'facevitals-${version}';
const URLS = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((r) => r || fetch(e.request)));
});
`;
      writeFileSync(join(outDir, 'sw.js'), sw);
      console.log(`sw.js: precaching ${urls.length} files (cache ${version})`);
    },
  };
}

export default defineConfig({
  base: './',
  plugins: [react(), precacheServiceWorker()],
  worker: { format: 'es' },
  server: { fs: { allow: ['..'] } },
  build: { target: 'es2022', chunkSizeWarningLimit: 1000 },
  test: { include: ['tests/**/*.test.ts'], environment: 'node' },
} as never);
